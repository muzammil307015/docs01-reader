import { FullDocumentAnalysis } from "../types";

export function exportAnalysisAsMarkdown(analysis: FullDocumentAnalysis): string {
  let md = `# DOCULENS ANALYSIS REPORT: ${analysis.title.toUpperCase()}\n\n`;
  md += `**Document Category:** ${analysis.category.replace("_", " ").toUpperCase()}\n`;
  md += `**Analysis Timestamp:** ${analysis.analyzedAt}\n`;
  md += `**Processing Pipeline:** ${analysis.processingMode.toUpperCase()}${analysis.modelUsed ? ` (${analysis.modelUsed})` : " (100% Deterministic Local Engine)"}\n\n`;

  md += `## 1. EXECUTIVE SUMMARY\n`;
  md += `${analysis.executiveSummary}\n\n`;

  md += `## 2. KEY DOCUMENT METRICS\n`;
  md += `- **Issuing Authority:** ${analysis.keyInfo.issuingOrganisation}\n`;
  md += `- **Document Reference:** ${analysis.keyInfo.referenceNumber || "N/A"}\n`;
  md += `- **Document Date:** ${analysis.keyInfo.documentDate}\n`;
  if (analysis.keyInfo.primaryContact) md += `- **Contact:** ${analysis.keyInfo.primaryContact}\n`;
  md += `\n`;

  md += `## 3. IMPORTANT DATES & DEADLINES\n`;
  if (analysis.importantDates.length === 0) {
    md += `*No explicit date stamps detected.*\n\n`;
  } else {
    analysis.importantDates.forEach(d => {
      md += `- **${d.label}:** ${d.rawText} [Type: ${d.type}] (Source: Page ${d.sourceLocation.page || 1})\n`;
      if (d.isExpired) md += `  ⚠️ *Status: Lapsed / Expired*\n`;
      else if (d.daysRemaining !== undefined) md += `  ⏳ *Remaining:* ${d.daysRemaining} days\n`;
    });
    md += `\n`;
  }

  md += `## 4. MANDATORY & OPTIONAL REQUIREMENTS\n`;
  md += `*Classification Key: FOUND = Evidence present in vault | MISSING = Action required | UNVERIFIED = Independent check needed*\n\n`;
  analysis.requirements.forEach((r, idx) => {
    md += `### ${idx + 1}. ${r.name} [${r.mandatory ? "MANDATORY" : "OPTIONAL"}]\n`;
    md += `- **Description:** ${r.description}\n`;
    md += `- **Source Location:** Page ${r.sourceLocation.page || 1}${r.sourceLocation.snippet ? ` ("${r.sourceLocation.snippet.slice(0, 80)}...")` : ""}\n`;
    md += `- **Verification Status:** ${r.verificationStatus}\n`;
    if (r.matchedEvidenceText) md += `- **Matched Evidence:** ${r.matchedEvidenceText}\n`;
    md += `\n`;
  });

  md += `## 5. FINANCIAL TERMS & OBLIGATIONS\n`;
  analysis.financialInformation.forEach(f => {
    md += `- **${f.label}:** ${f.amountText} (Page ${f.sourceLocation.page || 1})\n`;
  });
  md += `\n`;

  md += `## 6. RISK INDICATORS & WARNINGS\n`;
  analysis.risksAndWarnings.forEach(rw => {
    md += `- ⚠️ **[${rw.indicator.toUpperCase()} - ${rw.severity.toUpperCase()}] ${rw.title}**\n`;
    md += `  *Description:* ${rw.description}\n`;
    md += `  *Why Fired:* ${rw.whyFired}\n`;
    md += `  *Recommended Action:* ${rw.recommendedAction}\n`;
  });
  md += `\n`;

  md += `## 7. STEP-BY-STEP ACTION PLAN\n`;
  analysis.actionPlan.forEach(a => {
    md += `${a.stepNumber}. [ ] **${a.title}** (Priority: ${a.priority.toUpperCase()})\n`;
    md += `   ${a.description}\n`;
    if (a.officialDeadline) md += `   Cutoff: ${a.officialDeadline}\n`;
  });
  md += `\n`;

  md += `---\n`;
  md += `*Generated by DOCULENS Document Intelligence Platform. Output separates deterministic facts from AI interpretation. Not an endorsement of legal validity.*\n`;

  return md;
}

export function downloadFile(content: string, fileName: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function exportRequirementsAsCsv(analysis: FullDocumentAnalysis): void {
  const headers = [
    "Requirement ID",
    "Requirement Name",
    "Category",
    "Mandatory/Optional",
    "Verification Status",
    "Confidence",
    "Source Page",
    "Description",
    "Matched Evidence",
  ];

  const rows = analysis.requirements.map(r => [
    `"${r.id}"`,
    `"${r.name.replace(/"/g, '""')}"`,
    `"${(r.category || "").replace(/"/g, '""')}"`,
    r.mandatory ? "Mandatory" : "Optional",
    `"${r.verificationStatus}"`,
    `${Math.round(r.confidence * 100)}%`,
    `${r.sourceLocation.page || 1}`,
    `"${r.description.replace(/"/g, '""')}"`,
    `"${(r.matchedEvidenceText || "").replace(/"/g, '""')}"`,
  ]);

  const csvContent = [headers.join(","), ...rows.map(row => row.join(","))].join("\r\n");
  const fileName = `DOCULENS_Requirements_${analysis.title.replace(/[^a-zA-Z0-9]/g, "_").slice(0, 30)}.csv`;
  downloadFile(csvContent, fileName, "text/csv;charset=utf-8;");
}

export function exportChecklistAsCsv(analysis: FullDocumentAnalysis): void {
  const headers = ["Step", "Task Title", "Status", "Priority", "Cutoff Deadline", "Instructions"];
  const rows = analysis.actionPlan.map(a => [
    a.stepNumber,
    `"${a.title.replace(/"/g, '""')}"`,
    a.status.toUpperCase(),
    a.priority.toUpperCase(),
    `"${a.officialDeadline || "N/A"}"`,
    `"${a.description.replace(/"/g, '""')}"`,
  ]);

  const csvContent = [headers.join(","), ...rows.map(row => row.join(","))].join("\r\n");
  const fileName = `DOCULENS_Action_Checklist_${analysis.title.replace(/[^a-zA-Z0-9]/g, "_").slice(0, 30)}.csv`;
  downloadFile(csvContent, fileName, "text/csv;charset=utf-8;");
}

